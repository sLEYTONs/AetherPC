using System.Globalization;
using AetherPC.Core.Localization;

namespace AetherPC.Infrastructure.Localization;

/// <summary>
/// Catálogo ES/EN. Implementación de infraestructura; Core solo conoce ILocalizer.
/// </summary>
public sealed class CatalogLocalizer : ILocalizer
{
    private Dictionary<string, string> _map = Es;
    public string Language { get; private set; } = "es";
    public bool IsEnglish => Language == "en";

    public void SetLanguage(string? lang)
    {
        Language = string.Equals(lang, "en", StringComparison.OrdinalIgnoreCase) ? "en" : "es";
        _map = Language == "en" ? En : Es;
        try
        {
            // Inglés = cultura invariante (el runtime .NET no trae satélites en\).
            // Español = es\ (PresentationFramework.resources.dll, etc.).
            var ui = Language == "en"
                ? CultureInfo.InvariantCulture
                : CultureInfo.GetCultureInfo("es");
            CultureInfo.CurrentUICulture = ui;
            CultureInfo.CurrentCulture = ui;
            CultureInfo.DefaultThreadCurrentUICulture = ui;
            CultureInfo.DefaultThreadCurrentCulture = ui;
        }
        catch
        {
            /* */
        }
    }

    public string T(string key)
    {
        if (_map.TryGetValue(key, out var v) && !string.IsNullOrEmpty(v)) return v;
        // EN: never fall back to Spanish (avoids bilingual UI). ES may use EN as technical backup.
        if (!IsEnglish && En.TryGetValue(key, out var enFb) && !string.IsNullOrEmpty(enFb)) return enFb;
        return key;
    }

    public string T(string key, params object[] args)
    {
        try { return string.Format(T(key), args); }
        catch { return T(key); }
    }

    public bool Has(string key) => _map.ContainsKey(key) || Es.ContainsKey(key);

    public LocValidationResult Validate()
    {
        var missingEn = Es.Keys.Where(k => !En.ContainsKey(k) || string.IsNullOrWhiteSpace(En[k])).OrderBy(k => k).ToList();
        var missingEs = En.Keys.Where(k => !Es.ContainsKey(k) || string.IsNullOrWhiteSpace(Es[k])).OrderBy(k => k).ToList();
        var empty = Es.Where(kv => string.IsNullOrWhiteSpace(kv.Value)).Select(kv => kv.Key)
            .Concat(En.Where(kv => string.IsNullOrWhiteSpace(kv.Value)).Select(kv => kv.Key))
            .Distinct().OrderBy(k => k).ToList();
        return new LocValidationResult(missingEn, missingEs, empty);
    }

